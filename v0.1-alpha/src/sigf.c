const char* get_sig_name(int sig, char* buffer) {
    const char* name;
    switch(sig) {
        case SIGSEGV: name = "SEGMENTATION FAULT"; break;
        case SIGFPE:  name = "MATH ERROR";       break;
        case SIGILL:  name = "ILLEGAL INSTR";    break;
        case SIGBUS:  name = "BUS ERROR";        break;
        case SIGABRT: name = "ABORTED";          break;
        default:      name = "UNKNOWN SIGNAL";   break;
    }

    int i = 0;
    while (name[i] != '\0') { buffer[i] = name[i]; i++; }
    buffer[i++] = ' '; buffer[i++] = '(';

    if (sig < 10) {
        buffer[i++] = sig + '0';
    }
    else {
        buffer[i++] = (sig / 10) + '0';
        buffer[i++] = (sig % 10) + '0';
    }
    buffer[i++] = ')';
    buffer[i] = '\0';

    return buffer;
}

void atm_rsod(int sig, siginfo_t *si, void *unused) {
        int fd = open("/dev/fb0", O_RDWR);
        if (fd < 0) _exit(1);

        struct fb_var_screeninfo vinfo;
        ioctl(fd, FBIOGET_VSCREENINFO, &vinfo);

        uint32_t red = 0x0000FF;

        for(int i = 0; i < (vinfo.xres * vinfo.yres); i++) {
                write(fd, &red, 4);
        }

        char err_buf[64];
        const char* error_msg = get_sig_name(sig, err_buf);
        const char* title = "!!!KERNEL PANIC!!!";

        const char* texts[] = {title, error_msg};
        int y_pos = 50;

        for (int m = 0; m < 2; m++) {
        const char *str = texts[m];
        int x_pos = 50;
        while (*str) {
            unsigned char c = *str;
            if (c >= 32 && c <= 90) { // Font tablosundaki karakterler
                for (int r = 0; r < 8; r++) {
                    lseek(fd, (y_pos + r) * (vinfo.xres * 4) + (x_pos * 4), SEEK_SET);
                    unsigned char b = font8x8_basic[c - 32][r];
                    for (int col = 0; col < 8; col++) {
                        uint32_t color = (b & (1 << (7 - col))) ? 0xFFFFFF : 0x0000FF;
                        write(fd, &color, 4);
                    }
                }
            }
            x_pos += 10;
            str++;
        }
        y_pos += 20;
    }

    close(fd);
    _exit(1);
}


void atmsig_handle(int sig, siginfo_t *si, void *unused) {
	static int crash_count = 0;
    	crash_count++;
        
	printf("Critical error handled: Signal %d\n", sig, crash_count);

	if (crash_count >= 10) {
        	printf("Too many crashes. Halting process.\n");
        	sync();
        	_exit(1);
    	}

        switch(sig) {
                case SIGSEGV: printf("Reason: Segmentation fault\n"); break;
                case SIGFPE: printf("Reason: Invalid math operation\n"); break;
                case SIGILL: printf("Reason: Illegal instruction\n"); break;
                case SIGBUS: printf("Reason: Bus error\n"); break;
                default: printf("Reason: Unknown critical signal.\n"); break;
        }

        if (getpid() == 1) {
                atm_rsod(sig, si, NULL);
        }

        siglongjmp(jump_buffer, sig);
}

int set_sig() {
        struct sigaction sa;
        sa.sa_flags = SA_SIGINFO;
        sigemptyset(&sa.sa_mask);
        sa.sa_sigaction = atmsig_handle;

        sigaction(SIGSEGV, &sa, NULL);
        sigaction(SIGFPE,  &sa, NULL);
        sigaction(SIGILL,  &sa, NULL);
        sigaction(SIGBUS,  &sa, NULL);
        sigaction(SIGABRT, &sa, NULL);
}
